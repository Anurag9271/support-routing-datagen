# scripts/verify_reproducibility.ps1
# Generates dataset twice with identical seed 20261022, compares MANIFEST hashes, runs validator.
param(
    [switch]$full
)

$ErrorActionPreference = "Stop"

$PYTHON = ".venv\Scripts\python.exe"
if (-not (Test-Path $PYTHON)) {
    $PYTHON = "python"
}

$TMP_BASE = [System.IO.Path]::Combine([System.IO.Path]::GetTempPath(), "yottaflex_repro_" + [System.Guid]::NewGuid().ToString("N"))
$RUN1_DIR = [System.IO.Path]::Combine($TMP_BASE, "run1")
$RUN2_DIR = [System.IO.Path]::Combine($TMP_BASE, "run2")

try {
    Write-Host "============================================================================"
    Write-Host "                 YOTTAFLEX REPRODUCIBILITY VERIFICATION                     "
    Write-Host "============================================================================"

    $GEN_ARGS = @("--seed", "20261022")
    if ($full) {
        Write-Host "Mode: FULL SCALE (30,000 tickets)"
    } else {
        Write-Host "Mode: SMALL SCALE (300 tickets)"
        $GEN_ARGS += @("--tickets", "300", "--agents", "20", "--customers", "120", "--messages", "1000")
    }

    # Run 1
    Write-Host "`n[1/4] Generating first run into: $RUN1_DIR"
    & $PYTHON -m generator @GEN_ARGS --out "$RUN1_DIR"
    if ($LASTEXITCODE -ne 0) {
        throw "Run 1 generator failed with exit code $LASTEXITCODE"
    }

    # Run 2
    Write-Host "`n[2/4] Generating second run into: $RUN2_DIR"
    & $PYTHON -m generator @GEN_ARGS --out "$RUN2_DIR"
    if ($LASTEXITCODE -ne 0) {
        throw "Run 2 generator failed with exit code $LASTEXITCODE"
    }

    # Compare MANIFEST.json
    Write-Host "`n[3/4] Comparing MANIFEST.json hashes between Run 1 and Run 2..."
    $manifest1_path = Join-Path $RUN1_DIR "MANIFEST.json"
    $manifest2_path = Join-Path $RUN2_DIR "MANIFEST.json"

    if (-not (Test-Path $manifest1_path) -or -not (Test-Path $manifest2_path)) {
        throw "MANIFEST.json missing from output directories"
    }

    $m1 = Get-Content $manifest1_path -Raw | ConvertFrom-Json
    $m2 = Get-Content $manifest2_path -Raw | ConvertFrom-Json

    $mismatch = $false
    foreach ($file_key in $m1.files.psobject.Properties.Name) {
        $hash1 = $m1.files.$file_key.sha256
        $hash2 = $m2.files.$file_key.sha256
        if ($hash1 -ne $hash2) {
            Write-Host "HASH MISMATCH on file: $file_key ($hash1 vs $hash2)" -ForegroundColor Red
            $mismatch = $true
        }
    }

    if ($mismatch) {
        Write-Host "`nRESULT: FAIL - Output hashes differ between runs!" -ForegroundColor Red
        exit 1
    }
    Write-Host "All file SHA-256 hashes match identically between runs." -ForegroundColor Green

    # Run validator on both outputs
    Write-Host "`n[4/4] Running validator in evaluate mode on both outputs..."
    $gt1 = Join-Path $RUN1_DIR "ground_truth\ground_truth.csv"
    $gt2 = Join-Path $RUN2_DIR "ground_truth\ground_truth.csv"

    & $PYTHON -m validation.validate --mode evaluate --data "$RUN1_DIR" --ground-truth "$gt1"
    if ($LASTEXITCODE -ne 0) {
        throw "Validator failed on Run 1 output"
    }

    & $PYTHON -m validation.validate --mode evaluate --data "$RUN2_DIR" --ground-truth "$gt2"
    if ($LASTEXITCODE -ne 0) {
        throw "Validator failed on Run 2 output"
    }

    Write-Host "`n============================================================================"
    Write-Host "RESULT: PASS" -ForegroundColor Green
    Write-Host "Both runs generated byte-identical outputs and passed evaluation."
    Write-Host "============================================================================"
    exit 0
}
catch {
    Write-Host "`nError during verification: $_" -ForegroundColor Red
    Write-Host "RESULT: FAIL" -ForegroundColor Red
    exit 1
}
finally {
    if (Test-Path $TMP_BASE) {
        Remove-Item -Recurse -Force $TMP_BASE -ErrorAction SilentlyContinue
    }
}
