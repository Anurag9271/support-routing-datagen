#!/usr/bin/env bash
# scripts/verify_reproducibility.sh
# Generates dataset twice with identical seed 20261022, compares MANIFEST hashes, runs validator.

set -euo pipefail

PYTHON=".venv/bin/python"
if [ ! -f "$PYTHON" ]; then
    PYTHON=".venv/Scripts/python.exe"
fi
if [ ! -f "$PYTHON" ]; then
    PYTHON="python3"
fi

FULL_MODE=false
for arg in "$@"; do
    if [ "$arg" == "--full" ]; then
        FULL_MODE=true
    fi
done

TMP_BASE=$(mktemp -d -t yottaflex_repro_XXXXXX 2>/dev/null || mktemp -d)
RUN1_DIR="${TMP_BASE}/run1"
RUN2_DIR="${TMP_BASE}/run2"

cleanup() {
    rm -rf "${TMP_BASE}"
}
trap cleanup EXIT

echo "============================================================================"
echo "                 YOTTAFLEX REPRODUCIBILITY VERIFICATION                     "
echo "============================================================================"

GEN_ARGS=("--seed" "20261022")
if [ "$FULL_MODE" = true ]; then
    echo "Mode: FULL SCALE (30,000 tickets)"
else
    echo "Mode: SMALL SCALE (300 tickets)"
    GEN_ARGS+=("--tickets" "300" "--agents" "20" "--customers" "120" "--messages" "1000")
fi

echo ""
echo "[1/4] Generating first run into: ${RUN1_DIR}"
"$PYTHON" -m generator "${GEN_ARGS[@]}" --out "${RUN1_DIR}"

echo ""
echo "[2/4] Generating second run into: ${RUN2_DIR}"
"$PYTHON" -m generator "${GEN_ARGS[@]}" --out "${RUN2_DIR}"

echo ""
echo "[3/4] Comparing MANIFEST.json hashes between Run 1 and Run 2..."
"$PYTHON" -c "
import json, sys
m1 = json.load(open('${RUN1_DIR}/MANIFEST.json'))
m2 = json.load(open('${RUN2_DIR}/MANIFEST.json'))
diffs = []
for k, v in m1['files'].items():
    h1 = v['sha256']
    h2 = m2['files'].get(k, {}).get('sha256')
    if h1 != h2:
        diffs.append((k, h1, h2))
if diffs:
    print('DIFFS:', diffs)
    sys.exit(1)
" || {
    echo "RESULT: FAIL - File SHA-256 hashes differ between runs!"
    exit 1
}
echo "All file SHA-256 hashes match identically between runs."

echo ""
echo "[4/4] Running validator in evaluate mode on both outputs..."
"$PYTHON" -m validation.validate --mode evaluate --data "${RUN1_DIR}" --ground-truth "${RUN1_DIR}/ground_truth/ground_truth.csv"
"$PYTHON" -m validation.validate --mode evaluate --data "${RUN2_DIR}" --ground-truth "${RUN2_DIR}/ground_truth/ground_truth.csv"

echo ""
echo "============================================================================"
echo "RESULT: PASS"
echo "Both runs generated byte-identical outputs and passed evaluation."
echo "============================================================================"
exit 0
